static void fb_draw_glyph(uint32 x, uint32 y, uint8 ch, uint32 fg, uint32 bg) {
    const uint8* glyph = &g_font8x8[(uint32)ch * 8u];
    for (uint32 row = 0; row < 8; row++) {
        uint8 bits = glyph[row];
        for (uint32 col = 0; col < 8; col++) {
            uint32 color = (bits & (1u << (7u - col))) ? fg : bg;
            fb_put_pixel(x + col, y + row, color);
        }
    }

    fb_flush_rect(x, y, 8, 8);
}

void fb_simple_draw_glyph8x8(uint32 x, uint32 y, uint8 ch, uint8 r, uint8 g, uint8 b) {
    if (!g_fb_base) return;
    uint32 fg = fb_color(r, g, b);
    const uint8* glyph = &g_font8x8[(uint32)ch * 8u];
    for (uint32 row = 0; row < 8; row++) {
        uint8 bits = glyph[row];
        for (uint32 col = 0; col < 8; col++) {
            if (bits & (1u << (7u - col))) {
                fb_put_pixel(x + col, y + row, fg);
            }
        }
    }
}

void fb_simple_draw_glyph8x16_doubled(uint32 x, uint32 y, uint8 ch, uint8 r, uint8 g, uint8 b) {
    if (!g_fb_base) return;
    uint32 fg = fb_color(r, g, b);
    const uint8* glyph = &g_font8x8[(uint32)ch * 8u];
    for (uint32 row = 0; row < 8; row++) {
        uint8 bits = glyph[row];
        for (uint32 col = 0; col < 8; col++) {
            if (bits & (1u << (7u - col))) {
                fb_put_pixel(x + col, y + row * 2u + 0u, fg);
                fb_put_pixel(x + col, y + row * 2u + 1u, fg);
            }
        }
    }
}

int fb_simple_init(uint64 dtb_ptr) {
    uint64 base = 0;
    uint64 size = 0;
    uint32 width = 0;
    uint32 height = 0;
    uint32 stride = 0;
    char format[32];

    g_fb_last_error = FB_ERR_OK;
    if (fdt_parse_simple_framebuffer(dtb_ptr, &base, &size, &width, &height, &stride, format, sizeof(format)) != 0) {
        g_fb_last_error = FB_ERR_NO_SIMPLE_FB;
        /* QEMU virt + -device ramfb uses fw_cfg (etc/ramfb), not DT simple-framebuffer. */
        if (fb_try_init_qemu_ramfb(dtb_ptr) == 0) {
            return 0;
        }
        return -1;
    }

    g_fb_base = (volatile uint8*)(uint64)base;
    g_fb_width = width;
    g_fb_height = height;
    g_fb_stride = stride;
    g_fb_bpp = 4;

    for (uint32 i = 0; i < (uint32)sizeof(g_fb_format); i++) {
        g_fb_format[i] = '\0';
    }
    for (uint32 i = 0; i < (uint32)sizeof(g_fb_format) - 1 && format[i] != '\0'; i++) {
        g_fb_format[i] = format[i];
    }

    g_fb_fmt = FB_FMT_UNKNOWN;
    if (format[0] != '\0') {
        if (format[0] == 'x' && format[2] == 'r') {
            g_fb_fmt = FB_FMT_XRGB8888;
        } else if (format[0] == 'a' && format[2] == 'r') {
            g_fb_fmt = FB_FMT_ARGB8888;
        } else if (format[0] == 'x' && format[2] == 'b') {
            g_fb_fmt = FB_FMT_XBGR8888;
        }
    }

    g_fg_color = fb_color(255, 255, 255);
    g_bg_color = fb_color(0, 0, 0);

    fb_clear_screen();
    g_fb_last_error = FB_ERR_OK;
    return 0;
}

int fb_simple_ready(void) {
    return g_fb_base != 0;
}

void fb_simple_clear(void) {
    if (!g_fb_base) return;
    fb_clear_screen();
}

void fb_simple_set_rgb(uint8 r, uint8 g, uint8 b) {
    if (!g_fb_base) return;
    g_fg_color = fb_color(r, g, b);
}

void fb_simple_set_bg_rgb(uint8 r, uint8 g, uint8 b) {
    if (!g_fb_base) return;
    g_bg_color = fb_color(r, g, b);
}

void fb_simple_clear_rgb(uint8 r, uint8 g, uint8 b) {
    if (!g_fb_base) return;
    fb_fill_rect(0, 0, g_fb_width, g_fb_height, fb_color(r, g, b));
    fb_flush_rect(0, 0, g_fb_width, g_fb_height);
    g_cursor_x = 0;
    g_cursor_y = 0;
}

void fb_simple_draw_pixel(uint32 x, uint32 y, uint8 r, uint8 g, uint8 b) {
    if (!g_fb_base) return;
    if (x >= g_fb_width || y >= g_fb_height) return;
    fb_put_pixel(x, y, fb_color(r, g, b));
    fb_flush_rect(x, y, 1, 1);
}

void fb_simple_fill_rect(uint32 x, uint32 y, uint32 w, uint32 h, uint8 r, uint8 g, uint8 b) {
    if (!g_fb_base) return;
    if (w == 0 || h == 0) return;
    if (x >= g_fb_width || y >= g_fb_height) return;
    if (x + w > g_fb_width) w = g_fb_width - x;
    if (y + h > g_fb_height) h = g_fb_height - y;
    fb_fill_rect(x, y, w, h, fb_color(r, g, b));
    fb_flush_rect(x, y, w, h);
}

void fb_simple_flush(void) {
    if (!g_fb_base) return;
    fb_flush_rect(0, 0, g_fb_width, g_fb_height);
}

static void fb_newline(void) {
    g_cursor_x = 0;
    g_cursor_y += 8;
    if (g_cursor_y + 8 > g_fb_height) {
        fb_clear_screen();
    }
}

void fb_simple_putc(char c) {
    if (!g_fb_base) return;

    if (c == '\n') {
        fb_newline();
        return;
    }
    if (c == '\r') {
        g_cursor_x = 0;
        return;
    }

    /*
     * Control chars used by the shell line editor.
     * VGA text mode effectively treats these as cursor movement; do the same
     * for the ramfb console so editing doesn't print garbage glyphs.
     */
    if (c == '\b' || c == 0x7F) {
        if (g_cursor_x >= 8) {
            g_cursor_x -= 8;
        } else {
            g_cursor_x = 0;
        }
        fb_draw_glyph(g_cursor_x, g_cursor_y, (uint8)' ', g_fg_color, g_bg_color);
        return;
    }
    if (c == '\t') {
        /* 4-space tab stops (good enough for bring-up). */
        for (int i = 0; i < 4; i++) {
            fb_simple_putc(' ');
        }
        return;
    }

    if (g_cursor_x + 8 > g_fb_width) {
        fb_newline();
    }

    fb_draw_glyph(g_cursor_x, g_cursor_y, (uint8)c, g_fg_color, g_bg_color);
    g_cursor_x += 8;
}

void fb_simple_write(const char* s) {
    if (!s) return;
    while (*s) {
        fb_simple_putc(*s++);
    }
}

int fb_simple_get_info(uint64* out_base,
                       uint32* out_width,
                       uint32* out_height,
                       uint32* out_stride,
                       uint32* out_bpp,
                       const char** out_format) {
    if (!g_fb_base) return -1;
    if (out_base) *out_base = (uint64)(const void*)g_fb_base;
    if (out_width) *out_width = g_fb_width;
    if (out_height) *out_height = g_fb_height;
    if (out_stride) *out_stride = g_fb_stride;
    if (out_bpp) *out_bpp = g_fb_bpp;
    if (out_format) *out_format = (const char*)g_fb_format;
    return 0;
}

int fb_simple_last_error(void) {
    return g_fb_last_error;
}
